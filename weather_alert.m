% ThingSpeak MATLAB Analysis: Weather Station Email Alert
% Enter keys privately in ThingSpeak before running.
v = thingSpeakRead(3499317, 'Fields', [1 2 3], ...
    'NumPoints', 1, 'ReadKey', 'YOUR_CHANNEL_READ_KEY');
if numel(v) == 3 && v(3) == 1
    options = weboptions('HeaderFields', ...
        {'ThingSpeak-Alerts-API-Key', 'YOUR_ALERTS_API_KEY'});
    webwrite('https://api.thingspeak.com/alerts/send', ...
        'subject', 'Weather Station Alert', ...
        'body', sprintf(['Temperature %.1f C; humidity %.1f percent. ' ...
        'Limits: T >35 C or RH >80 percent.'], v(1), v(2)), options);
end
